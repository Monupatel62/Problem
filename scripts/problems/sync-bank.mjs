import { existsSync, readFileSync, writeFileSync } from "node:fs";
import path from "node:path";
import { loadStructuredProblems } from "./load-structured-problems.mjs";

const bankPath = path.join(process.cwd(), "src", "lib", "problems", "bank.ts");

function serialize(value) {
  return JSON.stringify(value, null, 2).replace(/\\\\n/g, "\\n");
}

function stripTrailingCommas(source) {
  let output = "";
  let inString = false;
  let escaped = false;

  for (let index = 0; index < source.length; index += 1) {
    const character = source[index];

    if (inString) {
      output += character;
      if (escaped) escaped = false;
      else if (character === "\\") escaped = true;
      else if (character === '"') inString = false;
      continue;
    }

    if (character === '"') {
      inString = true;
      output += character;
      continue;
    }

    if (character === ",") {
      let next = index + 1;
      while (/\s/.test(source[next] ?? "")) next += 1;
      if (source[next] === "]" || source[next] === "}") continue;
    }

    output += character;
  }

  return output;
}

function loadExistingProblems() {
  if (!existsSync(bankPath)) return [];

  const source = readFileSync(bankPath, "utf8");
  const match = source.match(/export const problemBank: ProblemDefinition\[\] = (\[[\s\S]*\]) as ProblemDefinition\[\];/);
  if (!match) throw new Error("Could not read the existing generated problem bank.");
  return JSON.parse(stripTrailingCommas(match[1]));
}

const structuredProblems = loadStructuredProblems();
const existingProblems = loadExistingProblems();
const structuredBySlug = new Map(structuredProblems.map((problem) => [problem.slug, problem]));
const existingSlugs = new Set(existingProblems.map((problem) => problem.slug));

// Structured content replaces its matching catalog record, while bank-only
// entries are retained. This avoids silently dropping valid catalog pages
// when only part of the problem bank has content folders.
const problems = [
  ...existingProblems.map((problem) => structuredBySlug.get(problem.slug) ?? problem),
  ...structuredProblems.filter((problem) => !existingSlugs.has(problem.slug)),
].sort((first, second) => first.id - second.id);

const output = `// This file is generated by scripts/problems/sync-bank.mjs.
// Edit src/content/problems/** instead, then run npm run problems:sync.

export type ProblemDifficulty = "Easy" | "Medium" | "Hard";

export type ProblemExample = {
  input: string;
  output: string;
  explanation?: string;
};

export type ProblemCase = {
  input: unknown[];
  expected: unknown;
};

export type ProblemDefinition = {
  id: number;
  slug: string;
  title: string;
  acceptance: string;
  difficulty: ProblemDifficulty;
  track: "Algorithms" | "Database" | "Shell" | "Concurrency";
  judgeReady?: boolean;
  tags: string[];
  companies?: string[];
  frequency?: number;
  premium?: boolean;
  likes?: number;
  dislikes?: number;
  discussionCount?: number;
  description: string;
  constraints: string[];
  hints: string[];
  examples: ProblemExample[];
  sampleCases: ProblemCase[];
  hiddenCases: ProblemCase[];
  functionName: string;
  starterCode: Record<string, string>;
  sqlSetup?: string[];
  isSql?: boolean;
  isShell?: boolean;
  isConcurrency?: boolean;
  editorial?: string[];
  solutionApproaches?: Array<{
    title: string;
    complexity: string;
    explanation: string;
  }>;
};

export const problemBank: ProblemDefinition[] = ${serialize(problems)} as ProblemDefinition[];

export function getProblemBySlug(slug: string) {
  return problemBank.find((problem) => problem.slug === slug);
}
`;

writeFileSync(bankPath, output);
console.log(`[sync-bank] wrote ${problems.length} problems to src/lib/problems/bank.ts (${structuredProblems.length} structured)`);
